"""Assemble README.md from README_top.md (hand-written verdict), tables.md (summarize.py), README_method.md, README_tail.md."""
import os

H = os.path.dirname(os.path.abspath(__file__))


def r(n):
    return open(os.path.join(H, n), encoding="utf-8").read()


mid = "\n\n# Tables\n\nGenerated by `summarize.py` from `raw/`. Q1-Q7 match the questions of the stage.\n\n"
open(os.path.join(H, "README.md"), "w", encoding="utf-8").write(
    r("README_top.md") + mid + r("tables.md") + "\n\n" + r("README_method.md") + r("README_tail.md"))
