"""Assemble README.md from the hand-written parts and the generated tables.  python make_readme.py"""
import os

H = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(H, "results")


def rd(p):
    f = os.path.join(H, p)
    return open(f, encoding="utf-8").read() if os.path.exists(f) else ""


parts = [rd("README_top.md"), rd("README_method.md")]
parts.append("## Results tables (generated by `report.py` from `results/raw/*.json`)\n")
parts.append("Plots (recall vs QPS, single thread and batched): `results/plots/<dataset>_<N>_{1t,batch}.png`.\n")
parts.append("### Recall versus QPS, build time and memory, per dataset and size\n\n" + rd("results/tables_cells.md"))
parts.append("### Exact search latency (10k / 100k / 1M)\n\n`median ms (1T)` is the pinned single-thread loop; `all-threads single query` lets the library use every core for one query at a time; `batch QPS` is a batched call on 32 logical CPUs.\n\n" + rd("results/tables_exact.md"))
parts.append("### Streaming mutation (insert 10k / update 10k / delete 10k on the built index)\n\nBatches of 1,000 through each system's own API. ISONGraph rows include index maintenance; numpy/faiss Flat have no index to maintain. `recall before` is 0.000 where no sweep point reached 0.95 (the highest nprobe was used).\n\n" + rd("results/tables_mutation.md"))
parts.append("### Filtered search (random 10% and 1% subsets)\n\n" + rd("results/tables_filter.md"))
parts.append("### Save / load and on-disk size\n\n" + rd("results/tables_saveload.md"))
f = rd("results/tables_failures.md")
parts.append("### Jobs that failed or timed out\n\n" + (f if f.count("\n") > 2 else "None in the final run.\n"))
parts.append(rd("README_tail.md"))
open(os.path.join(H, "README.md"), "w", encoding="utf-8").write("\n\n".join(parts))
print("README.md written,", sum(len(p) for p in parts), "chars")
